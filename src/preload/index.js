import { contextBridge, ipcRenderer } from 'electron'

// Everything the renderer can ask the main process for. Each call resolves
// to { ok: true, data } or { ok: false, error }.
contextBridge.exposeInMainWorld('ficBible', {
  getStatus: () => ipcRenderer.invoke('status:get'),
  libraryInfo: () => ipcRenderer.invoke('library:info'),
  chooseLibrary: () => ipcRenderer.invoke('library:choose'),
  importLibrary: () => ipcRenderer.invoke('library:import'),
  navigationTree: () => ipcRenderer.invoke('nav:tree'),
  libraryOverview: () => ipcRenderer.invoke('library:overview'),
  workOverview: (workId) => ipcRenderer.invoke('work:overview', workId),
  chapterOverview: (chapterId) => ipcRenderer.invoke('chapter:overview', chapterId),
  sceneDetail: (sceneId) => ipcRenderer.invoke('scene:detail', sceneId),
  sceneProse: (sceneId) => ipcRenderer.invoke('scene:prose', sceneId),
  sceneSource: (sceneId) => ipcRenderer.invoke('scene:source', sceneId),
  saveScene: (sceneId, text, baseHash) => ipcRenderer.invoke('scene:save', sceneId, text, baseHash),
  chapterProse: (chapterId) => ipcRenderer.invoke('chapter:prose', chapterId),
  exportChapter: (chapterId, format) => ipcRenderer.invoke('chapter:export', chapterId, format),
  createBeat: (sceneId, fields) => ipcRenderer.invoke('beat:create', sceneId, fields),
  updateBeat: (beatId, patch) => ipcRenderer.invoke('beat:update', beatId, patch),
  moveBeat: (beatId, direction) => ipcRenderer.invoke('beat:move', beatId, direction),
  editNotes: (sceneId) => ipcRenderer.invoke('editNote:list', sceneId),
  createEditNote: (sceneId, fields) => ipcRenderer.invoke('editNote:create', sceneId, fields),
  updateEditNote: (noteId, patch) => ipcRenderer.invoke('editNote:update', noteId, patch),
  deleteEditNote: (noteId) => ipcRenderer.invoke('editNote:delete', noteId),
  deleteBeat: (beatId) => ipcRenderer.invoke('beat:delete', beatId),
  updateScene: (sceneId, patch) => ipcRenderer.invoke('scene:update', sceneId, patch),
  updateChapter: (chapterId, patch) => ipcRenderer.invoke('chapter:update', chapterId, patch),
  updateWork: (workId, patch) => ipcRenderer.invoke('work:update', workId, patch),
  createWork: (title) => ipcRenderer.invoke('work:create', title),
  createChapter: (workId, title) => ipcRenderer.invoke('chapter:create', workId, title),
  createScene: (chapterId, title) => ipcRenderer.invoke('scene:create', chapterId, title),
  characterProfile: (characterId) => ipcRenderer.invoke('character:profile', characterId),
  createCharacter: (workId, name) => ipcRenderer.invoke('character:create', workId, name),
  updateCharacter: (characterId, patch) => ipcRenderer.invoke('character:update', characterId, patch),
  deleteCharacter: (characterId) => ipcRenderer.invoke('character:delete', characterId),
  createCharacterField: (characterId, fields) => ipcRenderer.invoke('characterField:create', characterId, fields),
  updateCharacterField: (fieldId, patch) => ipcRenderer.invoke('characterField:update', fieldId, patch),
  moveCharacterField: (fieldId, direction) => ipcRenderer.invoke('characterField:move', fieldId, direction),
  deleteCharacterField: (fieldId) => ipcRenderer.invoke('characterField:delete', fieldId),
  characterNotes: (characterId) => ipcRenderer.invoke('character:notes', characterId),
  saveCharacterNotes: (characterId, text, baseHash) =>
    ipcRenderer.invoke('character:saveNotes', characterId, text, baseHash),
  lineDictionary: (workId) => ipcRenderer.invoke('lines:list', workId),
  createLine: (workId, fields) => ipcRenderer.invoke('line:create', workId, fields),
  updateLine: (lineId, patch) => ipcRenderer.invoke('line:update', lineId, patch),
  deleteLine: (lineId) => ipcRenderer.invoke('line:delete', lineId),
  timeline: (workId) => ipcRenderer.invoke('timeline:list', workId),
  createTimelineEvent: (workId, fields) => ipcRenderer.invoke('timeline:create', workId, fields),
  updateTimelineEvent: (eventId, patch) => ipcRenderer.invoke('timeline:update', eventId, patch),
  moveTimelineEvent: (eventId, direction) => ipcRenderer.invoke('timeline:move', eventId, direction),
  deleteTimelineEvent: (eventId) => ipcRenderer.invoke('timeline:delete', eventId),
  createNotePage: (workId, name) => ipcRenderer.invoke('notePage:create', workId, name),
  renameNotePage: (pageId, name) => ipcRenderer.invoke('notePage:rename', pageId, name),
  moveNotePage: (pageId, direction) => ipcRenderer.invoke('notePage:move', pageId, direction),
  deleteNotePage: (pageId) => ipcRenderer.invoke('notePage:delete', pageId),
  notePage: (pageId) => ipcRenderer.invoke('notePage:read', pageId),
  saveNotePage: (pageId, text, baseHash) => ipcRenderer.invoke('notePage:save', pageId, text, baseHash),
  search: (query) => ipcRenderer.invoke('search:everything', query),
  suggestions: () => ipcRenderer.invoke('suggestions'),
  openLink: (url) => ipcRenderer.invoke('link:open', url)
})
